public class OneMoreEncore{
    public static int totalSongs(int SongsNumber){
        System.out.println("The Total Number Of Songs Is = "+SongsNumber);
        return SongsNumber + 1;
    }
    public static void main(String[] args){
        int totalSongsNums = totalSongs(9);
        System.out.print("The Total Numbers Of Songs Is = "+totalSongsNums);
    }
}