// It Is The Main , And Frist Class...
public class FristJavaProject{
    // It Is The Main Method (Function , Or Operation)...
    public static void main(String[] args){
        // It Is Used To Print A Statement Into The New Line...
        System.out.println("Hello EveryOne! , And Welcome To");
        // It Is Used To Print A Statement Into The Same Line...
        System.out.print("JAVA Programming Language...");
        System.out.println("There Are Different Escape Sequences In The Java Programming Language Like:");
        // "\n" : New Line , Is Used To Position The Screen Cursor To The New Line...
        System.out.println("Java Programming Language \nAnd\n Python Programming Language...");
        // "\r" : Carriage Return , Is Used To Position The Screen Cursor To The Begging Of The Same Line Not Advanced To The Next Line. , Any Characters After Carraige Return Overwrite The Character Previously At The Same Line...
        System.out.println("HTML Language\rCSS Language...");
        // \t : Horizontal Tab , Position The Screen Cursor To The Next Tab Stop...
        System.out.println("Mahmoud\tKhalid\tShabaan\tOmar...");
        // \\ : It Is Used To Print A BackSlash...
        System.out.println("\\Faculty Of Computer Science , And Information System...\\");
        // \' : It Is Used To Print A Single Quotations...
        System.out.println("\'24 Years Old...\'");
        // \" : It Is Used To Print A Double Quotations...
        System.out.println("\"8 Nassar Nassif\"");
        
    }
}